/** A box around EACH letter: circle, square, diamond or rounded square, in a light (soft) or dark (strong) tone. */
export const LETTER_BOX_IDS = [
  'l-circle-light',
  'l-circle-dark',
  'l-square-light',
  'l-square-dark',
  'l-diamond-light',
  'l-diamond-dark',
  'l-round-light',
  'l-round-dark',
] as const;
export type LetterBoxId = (typeof LETTER_BOX_IDS)[number];

/** A box around the selected word or line (one box around the whole selection). */
export const WORD_BOX_IDS = ['w-box-light', 'w-box-dark', 'w-pill-light', 'w-pill-dark', 'w-dashed', 'w-double', 'w-underline'] as const;
export type WordBoxId = (typeof WORD_BOX_IDS)[number];

/** A box around a whole paragraph (one line of the text block). */
export const PARAGRAPH_BOX_IDS = ['p-box-light', 'p-box-dark', 'p-round', 'p-dashed', 'p-double', 'p-leftbar', 'p-shadow'] as const;
export type ParagraphBoxId = (typeof PARAGRAPH_BOX_IDS)[number];

/** Boxes that may sit on a span (letters and words). */
export type SpanBoxId = LetterBoxId | WordBoxId;

export type BoxScope = 'letter' | 'word' | 'paragraph';

const has = (list: readonly string[], v: unknown): boolean => typeof v === 'string' && list.includes(v);

export const isColorId = (v: unknown): v is ColorId => has(COLOR_IDS, v);
export const isFontId = (v: unknown): v is FontId => has(FONT_IDS, v);
export const isSizeId = (v: unknown): v is SizeId => has(SIZE_IDS, v);
export const isLetterBoxId = (v: unknown): v is LetterBoxId => has(LETTER_BOX_IDS, v);
export const isWordBoxId = (v: unknown): v is WordBoxId => has(WORD_BOX_IDS, v);
export const isParagraphBoxId = (v: unknown): v is ParagraphBoxId => has(PARAGRAPH_BOX_IDS, v);
export const isSpanBoxId = (v: unknown): v is SpanBoxId => isLetterBoxId(v) || isWordBoxId(v);

/** Which kind of box an id is, or null for an id that is not in the catalog. */
export function boxScope(id: unknown): BoxScope | null {
  if (isLetterBoxId(id)) return 'letter';
  if (isWordBoxId(id)) return 'word';
  if (isParagraphBoxId(id)) return 'paragraph';
  return null;
}

/** The shape part of a letter box id (`l-circle-dark` -> `circle`) and its tone. Null for any other id. */
export function letterBoxParts(id: unknown): { shape: 'circle' | 'square' | 'diamond' | 'round'; tone: 'light' | 'dark' } | null {
  if (!isLetterBoxId(id)) return null;
  const [, shape, tone] = id.split('-');
  return { shape: shape as 'circle' | 'square' | 'diamond' | 'round', tone: tone as 'light' | 'dark' };
}
