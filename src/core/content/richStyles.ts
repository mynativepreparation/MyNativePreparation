// Catalog of the rich-text styles (DECISIONS Q26). Pure data + type guards, no imports: the files store only these ids,
// the reader (modules/reader) and the editor (modules/admin) map an id to a CSS class. Texts shown to people live in en.json.
//
// A style id is stored inside a text block like this (see core/content/inline.ts):
//   {c=red|coloured}   {f=serif|other font}   {x=l-circle-dark|boxed letters}   {s=xl|bigger}   {c=blue;f=serif|several at once}
//   {{x=p-dashed}}a whole line (paragraph) in a box
// An id that is not in this catalog is NOT a style: the text stays plain.

/** Text colours. T11k adds one light AND one dark value per colour to core/ui/tokens.ts (`ink*`, checked by contrast.test.ts), so dark mode stays readable. */
export const COLOR_IDS = ['red', 'orange', 'brown', 'green', 'teal', 'blue', 'purple', 'pink'] as const;
export type ColorId = (typeof COLOR_IDS)[number];

/** Text sizes of one span: `s` smaller, `l` large, `xl` extra large, `xxl` the biggest. No size = the normal size. */
export const SIZE_IDS = ['s', 'l', 'xl', 'xxl'] as const;
export type SizeId = (typeof SIZE_IDS)[number];

